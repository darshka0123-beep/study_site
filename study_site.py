def tutor_reply(message, history):
    contents = []
    for m in history:
        role = "user" if m["role"] == "user" else "model"
        contents.append(types.Content(role=role, parts=[types.Part(text=_text(m["content"]))]))
    contents.append(types.Content(role="user", parts=[types.Part(text=_text(message))]))
    try:
        return generate(contents, system=TUTOR_PROMPT)
    except Exception as e:
        return f"⚠️ Gemini hiccup: {e}"


# ---------- 2. Flashcards ----------
def card_html(title, body, color="#ffe4f1"):
    return f"""<div style="background:{color};color:#4a3552;border-radius:24px;padding:40px 28px;
    min-height:200px;text-align:center;font-size:1.3rem;box-shadow:0 6px 18px rgba(200,120,170,.25);">
    <div style="font-size:.8rem;letter-spacing:.15em;text-transform:uppercase;opacity:.6;margin-bottom:12px">{title}</div>
    {body}</div>"""


def render(state):
    if not state or not state["cards"]:
        return card_html("Your deck", "Paste notes above and hit Generate ✨")
    q = state["queue"]
    total = len(state["cards"])
    if not q:
        return card_html("Deck complete", f"🎉 You got all {total} cards! Generate a new deck or review again.", "#e0f7ea")
    c = state["cards"][q[0]]
    if state["flipped"]:
        body = card_html("Answer 💡", html.escape(c["a"]), "#e8e4ff")
    else:
        body = card_html("Question 🌸", html.escape(c["q"]))
    footer = f"<p style='text-align:center;opacity:.7'>Cards left: {len(q)} / {total} · Got it: {state['known']}</p>"
    return body + footer


def parse_cards(txt):
    txt = txt.strip()
    if txt.startswith("```"):
        txt = txt.strip("`").removeprefix("json").strip()
    data = json.loads(txt)
    if isinstance(data, dict):
        data = next(iter(data.values()))
    return [{"q": str(c["q"]), "a": str(c["a"])} for c in data]


def make_cards(notes, n):
    if not notes or not notes.strip():
        return None, card_html("Oops", "Paste some notes or a topic first 🌧️")
    prompt = (
        f"Create {int(n)} high-quality study flashcards from the material below. "
        "Mix definitions, 'why/how' questions, and application questions. Keep answers short. "
        'Return ONLY a JSON list like [{"q": "question", "a": "answer"}].\n\nMATERIAL:\n' + notes
    )
    try:
        cards = parse_cards(generate(prompt, as_json=True))
    except Exception as e:
        return None, card_html("Error", f"Couldn't make cards: {html.escape(str(e))}")
    state = {"cards": cards, "queue": list(range(len(cards))), "flipped": False, "known": 0}
    return state, render(state)


def flip(state):
    if state and state["queue"]:
        state["flipped"] = not state["flipped"]
    return state, render(state)


def got_it(state):
    if state and state["queue"]:
        state["queue"].pop(0)
        state["known"] += 1
        state["flipped"] = False
    return state, render(state)


def review_again(state):
    if state and state["queue"]:
        state["queue"].append(state["queue"].pop(0))
        state["flipped"] = False
    return state, render(state)


