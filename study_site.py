# ---------- 5. Rain sound ----------
def make_rain(path="rain.wav", sr=22050, secs=40):
    rng = np.random.default_rng(7)
    n = sr * secs
    white = rng.normal(0, 1, n)
    smooth = lambda x, k: np.convolve(x, np.ones(k) / k, mode="same")
    hiss = smooth(white, 2) - smooth(white, 30)
    rumble = smooth(white, 150) * 3
    drops = smooth((rng.random(n) < 0.0015) * rng.normal(0, 1, n) * 12, 5)
    swell = 0.8 + 0.2 * np.sin(np.linspace(0, 6 * np.pi, n))
    mix = (hiss * 0.6 + rumble * 0.25 + drops * 0.5) * swell
    mix = mix / np.max(np.abs(mix)) * 0.7
    fade = int(0.05 * sr)
    mix[:fade] *= np.linspace(0, 1, fade)
    mix[-fade:] *= np.linspace(1, 0, fade)
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr)
        w.writeframes((mix * 32767).astype(np.int16).tobytes())
    return path


