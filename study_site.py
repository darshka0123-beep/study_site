def generate(contents, system=None, as_json=False, retries=3):
    """Call Gemini with simple retry (free tier can rate-limit)."""
    cfg = types.GenerateContentConfig(
        system_instruction=system,
        temperature=0.7,
        response_mime_type="application/json" if as_json else None,
    )
    for i in range(retries):
        try:
            return ai.models.generate_content(model=MODEL, contents=contents, config=cfg).text
        except Exception as e:
            if i == retries - 1:
                raise
            time.sleep(2 * (i + 1))


def _text(content):
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return " ".join(p.get("text", "") if isinstance(p, dict) else str(p) for p in content)
    return str(content)


